"""Build an allowlisted Worker source tree; never copy local data or secrets."""
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "cloudflare"


def prepare():
    source = TARGET / "src"
    source.mkdir(parents=True, exist_ok=True)
    for name in ("app.py", "database.py", "d1_database.py", "worker.py", "worker_auth.py"):
        shutil.copy2(ROOT / name, source / name)
    for package in ("repositories", "services"):
        destination = source / package
        destination.mkdir(exist_ok=True)
        for path in (ROOT / package).glob("*.py"):
            shutil.copy2(path, destination / path.name)
    templates = {
        path.relative_to(ROOT / "templates").as_posix(): path.read_text(encoding="utf-8")
        for path in sorted((ROOT / "templates").rglob("*.html"))
    }
    (source / "worker_templates.py").write_text(
        "# Generated by scripts/prepare_cloudflare.py\nTEMPLATES = " + repr(templates) + "\n",
        encoding="utf-8",
    )
    shutil.copytree(ROOT / "static", TARGET / "public" / "static", dirs_exist_ok=True)
    print("Prepared cloudflare/src and cloudflare/public")


if __name__ == "__main__":
    prepare()
